#Gensim의 Word2Vec은 단어를 낮은 차원의 벡터 공간에 임베딩하는 모델. 
#비슷한 문맥에 등장하는 단어들이 가까운 벡터를 갖도록 학습함.
#Gensim 공식 문서도 Word2Vec 계열 알고리즘 지원
from gensim.models import Word2Vec
sentence =[
    ["짜장면","중식","면"],
    ["초밥","일식","생선","밥"],
    ["짬뽕","중식","면","해물"],
    ["갈비탕","한식","고기","국"],
    ["파스타","양식","면","토마토"]
]

model = Word2Vec(
    sentences= sentence * 10000000,
    vector_size=50, #단어를 50차원 벡터로 표현
    window=4,
    min_count=1,
    workers=4,
    sg=1
)

#모델 저장하기
model.save("food_w2v.model")
print("모델 저장 완료")

my_model = Word2Vec.load("food_w2v.model")

print(my_model.wv["짜장면"])
print(my_model.wv.most_similar("짬뽕"))
